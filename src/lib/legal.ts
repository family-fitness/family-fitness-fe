/** 동의 한 가지 — 법이 알리라는 네 가지(목적 · 항목 · 기간 · 거부할 권리와 불이익) */
export interface ConsentTerms {
  title: string;
  /** 누가 · 무슨 법에 따라 받는 동의인가 */
  lead: string;
  rows: { label: string; text: string }[];
  /** 거부할 권리와 거부하면 생기는 일 */
  refusal: string;
}

/**
 * 조항 안의 한 덩어리.
 * - 글 — 문단 하나. 항(①②)은 글 앞에 붙여 쓴다
 * - `items` — 호(1. 2.)
 * - `rows` — 표 한 줄. 가로로 넓은 표는 폰에서 읽히지 않아 「이름 · 값」 묶음으로 그린다
 */
export type LegalBlock = string | { items: string[] } | { rows: { label: string; text: string }[] };

/** 조 하나 — 번호(제1조)는 그릴 때 붙인다 */
export interface LegalArticle {
  title: string;
  body: LegalBlock[];
}

/** 방침 · 약관 한 편 */
export interface LegalDoc {
  title: string;
  /** 조항 앞의 글 */
  preamble?: string;
  articles: LegalArticle[];
  /** 부칙 — 번호 없이 맨 끝에 */
  addendum?: string[];
}

